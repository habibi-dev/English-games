const SVG_OPEN =
  '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">';

/** The SVG markup of an icon (empty for an unknown name). */
export function iconSvg(name) {
  const inner = ICONS[name];
  return inner ? `${SVG_OPEN}${inner}</svg>` : '';
}

/**
 * An icon as an element for `h()`: a span sized by its font size (1em), so it follows the text around it.
 * `className` adds a class to the span, e.g. a tile's own icon box.
 */
export function uiIcon(name, className = '') {
  const span = document.createElement('span');
  span.className = `ui-icon${className ? ` ${className}` : ''}`;
  span.setAttribute('aria-hidden', 'true');
  span.innerHTML = iconSvg(name);
  return span;
}

// Canvas drawing (the shareable result card): the icon's shapes as Path2D objects, made once per icon.
const pathCache = new Map();

function shapesOf(name) {
  if (pathCache.has(name)) return pathCache.get(name);
  const shapes = [];
  const inner = ICONS[name];
  if (inner && typeof DOMParser !== 'undefined') {
    const doc = new DOMParser().parseFromString(`<svg xmlns="http://www.w3.org/2000/svg">${inner}</svg>`, 'image/svg+xml');
    for (const el of doc.documentElement.children) {
      const attr = (key) => Number(el.getAttribute(key) ?? 0);
      if (el.tagName === 'path') shapes.push(new Path2D(el.getAttribute('d')));
      else if (el.tagName === 'circle') {
        const cx = attr('cx');
        const cy = attr('cy');
        const r = attr('r');
        shapes.push(new Path2D(`M${cx - r} ${cy} A${r} ${r} 0 1 0 ${cx + r} ${cy} A${r} ${r} 0 1 0 ${cx - r} ${cy}`));
      } else if (el.tagName === 'line') {
        shapes.push(new Path2D(`M${attr('x1')} ${attr('y1')} L${attr('x2')} ${attr('y2')}`));
      } else if (el.tagName === 'rect') {
        const x = attr('x');
        const y = attr('y');
        const w = attr('width');
        const height = attr('height');
        shapes.push(new Path2D(`M${x} ${y} H${x + w} V${y + height} H${x} Z`));
      }
    }
  }
  pathCache.set(name, shapes);
  return shapes;
}

/** Draws an icon on a canvas, centred on (cx, cy), `size` pixels square, stroked in `color`. */
export function drawIcon(ctx, name, cx, cy, size, color) {
  const shapes = shapesOf(name);
  if (!shapes.length) return;
  const scale = size / 24;
  ctx.save();
  ctx.translate(cx - size / 2, cy - size / 2);
  ctx.scale(scale, scale);
  ctx.strokeStyle = color;
  ctx.lineWidth = 2;
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  for (const shape of shapes) ctx.stroke(shape);
  ctx.restore();
}
